void main() {
  test('client, references, items and batches from a real capture', () {
    final h = ClientHeaderExtractor.extract(_lines);
    expect(h.prefix, 'NCR.326');
    expect(h.name, 'Philippine Red Cross National Blood Center-NBC Tower');
    expect(h.address, '37 Edsn Corner Boni Avenue Mandalyong PHILIPPINES');

    final r = ItemTableParser.parse(_lines);
    expect(r.items.map((i) => (i.itemCode, i.qty, i.unit)), [
      ('B36845', 6.0, 'BOX'),
      ('B36846', 5.0, 'BOTTLE'),
      ('B36868', 6.0, 'BOTTLE'),
    ]);
    expect(r.items[2].description, 'DxH 5O0 Cleaner 500ml');
    expect([
      for (final i in r.items)
        for (final b in i.batches) (b.batchSerial, b.batchQuantity, b.expiryDate)
    ], [
      ('0179170', 6.0, '07/18/2027'),
      ('8300114', 5.0, '07/05/2027'),
      ('7704315', 6.0, '08/06/2027'),
    ]);
    expect(r.unsure, {2}, reason: 'item 3 batch quantity was not read');

    expect(
      OneScanReferencePatterns.fromLines(_lines, DocumentReferenceExtractor(),
          excludeTexts: r.tableTexts),
      containsAll(['SINo.:700014771', 'PONo.:PO-018561', 'DRNo.:690014771']),
    );
  });
}
